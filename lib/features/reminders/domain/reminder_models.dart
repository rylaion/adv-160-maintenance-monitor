/// User-configurable notification preferences.
class NotificationPreferences {
  const NotificationPreferences({
    this.enabled = true,
    this.notifyUpcoming = true,
    this.notifyDue = true,
    this.notifyOverdue = true,
    this.notifyDateBased = true,
    this.notifyCustom = true,
  });

  final bool enabled;
  final bool notifyUpcoming;
  final bool notifyDue;
  final bool notifyOverdue;
  final bool notifyDateBased;
  final bool notifyCustom;

  bool allows(ReminderType type) {
    if (!enabled) return false;
    return switch (type) {
      ReminderType.upcoming => notifyUpcoming,
      ReminderType.due => notifyDue,
      ReminderType.overdue => notifyOverdue,
      ReminderType.dateBased => notifyDateBased,
      ReminderType.custom => notifyCustom,
    };
  }

  NotificationPreferences copyWith({
    bool? enabled,
    bool? notifyUpcoming,
    bool? notifyDue,
    bool? notifyOverdue,
    bool? notifyDateBased,
    bool? notifyCustom,
  }) =>
      NotificationPreferences(
        enabled: enabled ?? this.enabled,
        notifyUpcoming: notifyUpcoming ?? this.notifyUpcoming,
        notifyDue: notifyDue ?? this.notifyDue,
        notifyOverdue: notifyOverdue ?? this.notifyOverdue,
        notifyDateBased: notifyDateBased ?? this.notifyDateBased,
        notifyCustom: notifyCustom ?? this.notifyCustom,
      );

  Map<String, dynamic> toJson() => {
        'enabled': enabled,
        'notifyUpcoming': notifyUpcoming,
        'notifyDue': notifyDue,
        'notifyOverdue': notifyOverdue,
        'notifyDateBased': notifyDateBased,
        'notifyCustom': notifyCustom,
      };

  factory NotificationPreferences.fromJson(Map<String, dynamic> m) =>
      NotificationPreferences(
        enabled: m['enabled'] as bool? ?? true,
        notifyUpcoming: m['notifyUpcoming'] as bool? ?? true,
        notifyDue: m['notifyDue'] as bool? ?? true,
        notifyOverdue: m['notifyOverdue'] as bool? ?? true,
        notifyDateBased: m['notifyDateBased'] as bool? ?? true,
        notifyCustom: m['notifyCustom'] as bool? ?? true,
      );
}

/// Domain model for a persisted maintenance reminder.
class MaintenanceReminder {
  const MaintenanceReminder({
    required this.id,
    required this.motorcycleId,
    required this.reminderType,
    required this.title,
    required this.dedupeKey,
    required this.status,
    this.itemId,
    this.ruleId,
    this.body,
    this.dueDate,
    this.dueOdometerKm,
    this.notifiedAt,
  });

  final int id;
  final int motorcycleId;
  final int? itemId;
  final int? ruleId;
  final ReminderType reminderType;
  final String title;
  final String? body;
  final DateTime? dueDate;
  final int? dueOdometerKm;
  final String dedupeKey;
  final ReminderStatus status;
  final DateTime? notifiedAt;

  bool get isAutoGenerated => dedupeKey.startsWith('auto:');
  bool get isCustom => reminderType == ReminderType.custom;
}

